export function getProductKeywords(product) {
  if (!product) return SEO_KEYWORDS.generic.join(", ");
  const vendor = (product.vendor || "").trim();
  const title = (product.title || "").trim();
  const type = (product.product_type || "").toLowerCase();
  const list = new Set([
    `${title} kaufen`,
    `${vendor} ${title}`,
    `${vendor} Deutschland`,
  ]);
  if (SEO_KEYWORDS.brands[vendor]) {
    list.add(SEO_KEYWORDS.brands[vendor].primary);
    SEO_KEYWORDS.brands[vendor].secondary.slice(0, 3).forEach((k) => list.add(k));
  }
  if (type.includes("liquid")) {
    list.add(SEO_KEYWORDS.productTypes.EJUICE.primary);
    list.add("shortfill e-liquid deutschland");
  } else if (type.includes("coil") || type.includes("pod")) {
    list.add(SEO_KEYWORDS.productTypes.COILS.primary);
    list.add(SEO_KEYWORDS.productTypes.CARTRIDGES.primary);
  } else if (type.includes("einweg")) {
    list.add(SEO_KEYWORDS.productTypes.DISPOSABLES.primary);
  } else {
    list.add(SEO_KEYWORDS.productTypes.STARTER_KITS.primary);
  }
  list.add("Mr. Nice Vape Deutschland");
  return [...list].slice(0, 12).join(", ");
}

